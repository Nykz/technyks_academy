/*
 * Regenerates api/src/app/prisma/bootstrap-schema.ts from prisma/schema.prisma.
 *
 * Hostinger cannot always execute Prisma's schema-engine binary, so
 * `prisma db push` may be skipped during the build. The API therefore creates
 * any missing tables itself at startup using this SQL, which runs through the
 * normal query connection. Re-run after every schema.prisma change:
 *
 *   node scripts/generate-bootstrap-schema.cjs
 */
const { execFileSync } = require('node:child_process');
const { writeFileSync } = require('node:fs');
const { join } = require('node:path');

const root = join(__dirname, '..');
const sql = execFileSync(
  process.execPath,
  [
    join(root, 'node_modules', 'prisma', 'build', 'index.js'),
    'migrate',
    'diff',
    '--from-empty',
    '--to-schema-datamodel',
    join(root, 'prisma', 'schema.prisma'),
    '--script',
  ],
  { cwd: root, encoding: 'utf8', env: { ...process.env, PRISMA_HIDE_UPDATE_MESSAGE: '1' } },
);

const statements = sql
  .split(/;\s*(?:\r?\n|$)/)
  .map((statement) => statement.replace(/^\s*--.*$/gm, '').trim())
  .filter(Boolean);

const tables = [];
const foreignKeys = [];
for (const statement of statements) {
  const create = statement.match(/^CREATE TABLE `([^`]+)`/);
  const alter = statement.match(/^ALTER TABLE `([^`]+)` ADD CONSTRAINT/);
  if (create) tables.push({ name: create[1], sql: statement });
  else if (alter) foreignKeys.push({ table: alter[1], sql: statement });
  else throw new Error(`Unexpected statement in generated SQL:\n${statement}`);
}

const output = `// GENERATED by scripts/generate-bootstrap-schema.cjs from prisma/schema.prisma.
// Do not edit by hand; re-run the script after changing the Prisma schema.

export const BOOTSTRAP_TABLES: { name: string; sql: string }[] = ${JSON.stringify(tables, null, 2)};

export const BOOTSTRAP_FOREIGN_KEYS: { table: string; sql: string }[] = ${JSON.stringify(foreignKeys, null, 2)};
`;

writeFileSync(join(root, 'api', 'src', 'app', 'prisma', 'bootstrap-schema.ts'), output);
console.log(`Wrote ${tables.length} tables and ${foreignKeys.length} foreign keys.`);
